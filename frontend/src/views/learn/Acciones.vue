      <p class="text-gray-700 leading-relaxed mb-4">
        En las acciones, muchas veces no pierde dinero quien no sabe, sino quien no controla sus emociones. Dos
        comportamientos arruinan a la mayoría de los principiantes: comprar por FOMO y vender por pánico.
      </p>

      <div class="bg-orange-50 border border-orange-200 rounded-xl p-4 mb-4">
        <h3 class="font-semibold text-orange-800 mb-2">Comprar por FOMO</h3>
        <p class="text-sm text-orange-900 mb-2">
          FOMO viene del inglés "fear of missing out", o miedo a quedarse fuera. Pasa cuando ves que una acción está
          subiendo mucho, todos hablan de ella y sientes que te estás perdiendo la oportunidad. Entonces compras tarde,
          cuando ya está cara, solo por no quedarte fuera.
        </p>
        <p class="text-sm text-orange-900">
          El problema es que muchas veces compras justo en el punto más alto, y cuando el precio se corrige, terminas
          perdiendo. Comprar por emoción y no por análisis casi siempre sale mal.
        </p>
      </div>

      <div class="bg-red-50 border border-red-200 rounded-xl p-4 mb-4">
        <h3 class="font-semibold text-red-800 mb-2">Vender por pánico</h3>
        <p class="text-sm text-red-900 mb-2">
          La venta por pánico ocurre cuando ves que tu inversión baja, te asustas y vendes rápido para "no perder
          más". El problema es que en renta variable las bajadas son normales y muchas veces temporales.
        </p>
        <p class="text-sm text-red-900">
          Si vendes asustado, conviertes una pérdida temporal (en papel) en una pérdida real. Mucha gente vende en el
          peor momento y luego ve cómo la acción se recupera sin ellos.
        </p>
      </div>

      <p class="text-gray-700 leading-relaxed">
        La clave es decidir con calma y con un plan, no por lo que sientes en el momento. Si compraste una empresa
        porque la analizaste y crees en ella a largo plazo, una bajada temporal no debería hacerte vender por miedo.
      </p>
    </section>

