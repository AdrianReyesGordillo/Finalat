        <li>Asegúrate de tener tus finanzas en orden y un fondo de emergencia antes de invertir.</li>
        <li>Elige una casa de bolsa o broker regulado y abre tu cuenta (suele ser 100% en línea).</li>
        <li>Deposita el dinero que vas a invertir, nunca dinero que necesites pronto.</li>
        <li>Busca la acción o el ETF que quieres comprar usando su clave o nombre.</li>
        <li>Define cuánto quieres invertir y confirma la compra.</li>
        <li>Da seguimiento con calma, sin revisar el precio cada hora.</li>
      </ol>
    </section>

    <!-- Cómo analizar -->
    <section class="mb-8">
