    <p class="text-gray-500 mb-6">Todo lo que necesitas entender antes de comprar tu primera acción: qué son, dónde comprarlas, cómo analizarlas y cómo controlar tus emociones al invertir.</p>

    <!-- Qué son -->
    <section class="mb-8">
      <h2 class="text-xl font-bold text-[#2D2B6B] mt-8 mb-3">¿Qué es una acción?</h2>
      <p class="text-gray-700 leading-relaxed mb-4">
        Una acción es una pequeña parte de una empresa. Cuando compras una acción, te conviertes en dueño de una
        fracción muy pequeña de esa compañía. No importa si es enorme como Apple o si es una empresa mexicana que
        cotiza en la bolsa: al tener una acción, eres socio en esa proporción.
      </p>
      <p class="text-gray-700 leading-relaxed">
        Eso significa que participas en lo que le pase a la empresa. Si crece y vale más, tus acciones pueden subir de
        precio. Si tiene problemas, pueden bajar. Por eso las acciones son parte de la renta variable: su valor cambia
        con el tiempo y no está garantizado.
      </p>
    </section>

    <!-- Qué es un ETF -->
    <section class="mb-8">
      <h2 class="text-xl font-bold text-[#2D2B6B] mt-8 mb-3">¿Qué es un ETF?</h2>
      <p class="text-gray-700 leading-relaxed mb-4">
        Un ETF (del inglés "Exchange Traded Fund", o fondo cotizado en bolsa) es como una canasta que dentro tiene
        muchas acciones de diferentes empresas. Cuando compras un ETF, con una sola operación estás comprando un
        pedacito de todas las empresas que hay dentro de esa canasta.
      </p>
      <p class="text-gray-700 leading-relaxed mb-4">
        Por ejemplo, existe un ETF muy conocido que sigue al índice S&P 500, que agrupa a las 500 empresas más
        grandes de Estados Unidos. Si compras ese ETF, en la práctica estás invirtiendo en las 500 empresas al mismo
        tiempo, sin tener que comprarlas una por una.
      </p>
      <p class="text-gray-700 leading-relaxed">
        Los ETFs se compran y se venden en la bolsa igual que una acción, desde la misma app de tu casa de bolsa, y
        normalmente puedes empezar con cantidades pequeñas.
      </p>
    </section>

    <!-- Por qué el ETF es bueno para diversificar -->
    <section class="mb-8">
      <h2 class="text-xl font-bold text-[#2D2B6B] mt-8 mb-3">¿Por qué un ETF es bueno para diversificar?</h2>
      <p class="text-gray-700 leading-relaxed mb-4">
        Diversificar significa repartir tu dinero en muchas inversiones distintas para no depender de una sola. Si
        compras la acción de una sola empresa y a esa empresa le va mal, todo tu dinero se ve afectado. En cambio, con
        un ETF tu dinero ya está repartido entre decenas o cientos de empresas.
      </p>
      <p class="text-gray-700 leading-relaxed mb-4">
        Esto hace que el ETF sea ideal para quien empieza, por varias razones:
      </p>
      <ul class="list-disc list-inside text-gray-700 space-y-2 mb-4">
        <li><strong>Reduce el riesgo:</strong> si a una empresa le va mal, las demás del ETF pueden compensar esa caída.</li>
        <li><strong>Es muy sencillo:</strong> no tienes que analizar empresa por empresa ni elegir la "ganadora".</li>
        <li><strong>Accesible:</strong> con poco dinero ya quedas invertido en muchas empresas a la vez.</li>
        <li><strong>Comisiones bajas:</strong> la mayoría de los ETFs cobran muy poco por administrarlos.</li>
      </ul>
      <div class="bg-[#F0F0FA] border border-[#E0E0F0] rounded-xl p-4">
        <p class="text-sm text-gray-700">
          En pocas palabras: comprar una sola acción es apostar por una empresa; comprar un ETF es apostar por todo un
          grupo de empresas a la vez. Por eso muchos inversionistas principiantes empiezan con ETFs antes de elegir
          acciones individuales.
        </p>
      </div>
    </section>

    <!-- Cómo funcionan -->
    <section class="mb-8">
      <h2 class="text-xl font-bold text-[#2D2B6B] mt-8 mb-3">¿Cómo funcionan las acciones?</h2>
      <p class="text-gray-700 leading-relaxed mb-4">
        Las acciones se compran y se venden en un lugar llamado bolsa de valores. En México la principal es la Bolsa
        Mexicana de Valores (BMV), y en Estados Unidos están la NYSE y el Nasdaq, donde cotizan muchas de las empresas
        más conocidas del mundo.
      </p>
      <p class="text-gray-700 leading-relaxed mb-4">
        El precio de una acción se mueve por la oferta y la demanda. Si mucha gente quiere comprar una acción, su
        precio tiende a subir. Si mucha gente quiere venderla, tiende a bajar. Esa demanda depende de muchas cosas:
        las ganancias de la empresa, las noticias, la economía y hasta las emociones de los inversionistas.
      </p>
      <p class="text-gray-700 leading-relaxed mb-4">
        Existen dos formas principales de ganar dinero con acciones:
      </p>
      <ul class="list-disc list-inside text-gray-700 space-y-2">
        <li><strong>Plusvalía:</strong> compras una acción a cierto precio y, si sube, la vendes más cara. La diferencia es tu ganancia.</li>
        <li><strong>Dividendos:</strong> algunas empresas reparten parte de sus ganancias entre sus accionistas. Es un pago periódico solo por tener la acción.</li>
      </ul>
    </section>

    <!-- Dónde comprar -->
    <section class="mb-8">
      <h2 class="text-xl font-bold text-[#2D2B6B] mt-8 mb-3">¿Dónde comprar acciones?</h2>
      <p class="text-gray-700 leading-relaxed mb-4">
        No puedes ir directo a la bolsa a comprar acciones. Necesitas un intermediario autorizado llamado casa de
        bolsa o broker. Hoy existen aplicaciones que hacen este proceso muy sencillo desde tu celular.
      </p>
      <p class="text-gray-700 leading-relaxed mb-4">
        En México algunas de las opciones más usadas son:
      </p>
      <ul class="list-disc list-inside text-gray-700 space-y-2 mb-4">
        <li><strong>GBM+:</strong> una de las más populares, permite invertir desde cantidades pequeñas en acciones mexicanas y de Estados Unidos.</li>
        <li><strong>Kuspit, Bursanet, Actinver:</strong> casas de bolsa con plataformas para invertir en línea.</li>
        <li><strong>Nu y otras fintech:</strong> han empezado a ofrecer compra de acciones dentro de sus apps.</li>
        <li><strong>Brokers internacionales:</strong> como Interactive Brokers, enfocados en mercados extranjeros.</li>
      </ul>
      <div class="bg-[#F0F0FA] border border-[#E0E0F0] rounded-xl p-4">
        <p class="text-sm text-[#2D2B6B] font-medium mb-1">Antes de elegir un broker, revisa:</p>
        <ul class="text-sm text-gray-700 space-y-1 list-disc list-inside">
          <li>Que esté regulado en México por la CNBV (o por un regulador serio si es extranjero).</li>
          <li>Las comisiones por compra, venta y manejo de cuenta.</li>
          <li>El monto mínimo para empezar.</li>
          <li>A qué mercados te da acceso (México, Estados Unidos, etc.).</li>
        </ul>
      </div>
    </section>

    <!-- Cómo empezar -->
    <section class="mb-8">
      <h2 class="text-xl font-bold text-[#2D2B6B] mt-8 mb-3">¿Cómo empezar paso a paso?</h2>
