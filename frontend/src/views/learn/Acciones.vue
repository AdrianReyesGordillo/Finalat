      </p>
      <ul class="list-disc list-inside text-gray-700 space-y-2">
        <li>¿Entiendo a qué se dedica la empresa y cómo gana dinero?</li>
        <li>¿Sus ventas y ganancias han crecido en los últimos años?</li>
        <li>¿Tiene una deuda manejable o demasiada?</li>
        <li>¿Es líder en su sector o tiene una ventaja frente a sus competidores?</li>
        <li>¿El precio actual es razonable comparado con lo que gana la empresa?</li>
      </ul>
    </section>

    <!-- Indicadores básicos -->
    <section class="mb-8">
      <h2 class="text-xl font-bold text-[#2D2B6B] mt-8 mb-3">Indicadores básicos que conviene conocer</h2>
      <p class="text-gray-700 leading-relaxed mb-4">
        No necesitas ser experto, pero hay algunos términos que verás seguido y conviene entender:
      </p>
      <ul class="list-disc list-inside text-gray-700 space-y-2">
        <li><strong>Precio/Utilidad (P/U o P/E):</strong> compara el precio de la acción con lo que gana la empresa. Ayuda a ver si está cara o barata.</li>
