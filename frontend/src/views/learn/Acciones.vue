        <li><strong>Invierte solo lo que no necesitas pronto:</strong> así no te ves obligado a vender en mal momento.</li>
        <li><strong>No revises el precio cada hora:</strong> eso genera ansiedad y decisiones impulsivas.</li>
        <li><strong>Piensa a largo plazo:</strong> las bajadas de corto plazo importan menos cuando inviertes para varios años.</li>
        <li><strong>Invierte poco a poco:</strong> comprar montos pequeños de forma constante reduce el riesgo de entrar en un mal momento.</li>
      </ul>
    </section>

    <!-- Inversión constante -->
    <section class="mb-8">
