      <p class="text-gray-700 leading-relaxed mb-4">
        Comprar una acción sin investigar es como comprar una casa sin verla. Existen dos formas principales de
        analizar una acción, y lo ideal es entender un poco de ambas.
      </p>

      <div class="grid md:grid-cols-2 gap-4 mb-4">
        <div class="bg-white border border-[#E0E0F0] rounded-xl p-4">
