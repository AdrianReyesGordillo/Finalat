      <p class="text-gray-700 leading-relaxed mb-4">
        Una de las formas más sencillas y efectivas para principiantes es invertir una cantidad fija de dinero cada
        cierto tiempo, por ejemplo cada mes, sin importar si el precio subió o bajó.
      </p>
      <p class="text-gray-700 leading-relaxed">
        Con esto a veces compras caro y a veces barato, pero a largo plazo el precio promedio tiende a equilibrarse.
        Además, te quita la presión de adivinar el momento perfecto para comprar, algo que ni los expertos logran
        hacer siempre.
      </p>
    </section>

