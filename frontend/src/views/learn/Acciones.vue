          <p class="text-sm text-gray-600 mb-2">
            Estudia si la empresa es buena y sana por dentro. Te preguntas: ¿gana dinero?, ¿tiene muchas deudas?,
            ¿está creciendo?, ¿tiene futuro?
          </p>
          <p class="text-sm text-gray-600">Es el más recomendable para quien invierte a largo plazo.</p>
        </div>
        <div class="bg-white border border-[#E0E0F0] rounded-xl p-4">
          <h3 class="font-semibold text-[#2D2B6B] mb-2">Análisis técnico</h3>
          <p class="text-sm text-gray-600 mb-2">
            Estudia el comportamiento del precio en gráficas para intentar predecir hacia dónde se moverá. Lo usan
            más quienes compran y venden en plazos cortos.
          </p>
          <p class="text-sm text-gray-600">Requiere más experiencia y suele combinarse con trading.</p>
        </div>
      </div>

