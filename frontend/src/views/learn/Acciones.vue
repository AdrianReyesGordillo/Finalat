        <li><strong>Dividend yield:</strong> qué porcentaje del precio te paga la empresa en dividendos al año.</li>
        <li><strong>Deuda:</strong> cuánto debe la empresa. Demasiada deuda puede ser una señal de riesgo.</li>
        <li><strong>Crecimiento de ingresos:</strong> si la empresa vende cada vez más con el paso del tiempo.</li>
      </ul>
    </section>

    <!-- Diversificación -->
    <section class="mb-8">
      <h2 class="text-xl font-bold text-[#2D2B6B] mt-8 mb-3">No pongas todo en una sola acción</h2>
